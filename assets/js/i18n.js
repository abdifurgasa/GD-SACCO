let currentLang = 'en';

function setLanguage(lang) {
    currentLang = lang;
    const t = translations[lang];
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t[key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = t[key];
            } else {
                el.innerHTML = t[key];
            }
        }
    });
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });
    localStorage.setItem('sacco-lang', lang);
}

function initLanguage() {
    const saved = localStorage.getItem('sacco-lang') || navigator.language.split('-')[0];
    const valid = ['en','am','om'];
    setLanguage(valid.includes(saved) ? saved : 'en');
}

// Event listeners for language switcher buttons
document.addEventListener('DOMContentLoaded', function() {
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', function() {
            setLanguage(this.dataset.lang);
        });
    });
    // Also listen for clicks on dynamically added buttons (if any)
});

// Expose globally
window.translations = translations;
window.setLanguage = setLanguage;
window.initLanguage = initLanguage;
